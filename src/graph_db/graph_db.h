/*
 * graph_db.h — umbrella header of the kimix-graph-db library.
 *
 * Includes the whole in-memory layer plus the cold-storage glue:
 *   vertex.h  — Vertex: identity, opaque content blob, dependency links, the
 *               per-vertex shared lock and the dirty flag.
 *   graph.h   — Graph: the vertex container, structural CRUD, traversal
 *               (BFS has_path / shortest_path), roots and the two-level
 *               concurrency contract (read it before calling anything).
 *   utils.h     — key scheme, vertex-record codec and ColdStorage (LMDB).
 *   serialize.h — GraphSerializer (parallel incremental save) and
 *                 GraphDeserializer (dual-stage, cycle/corruption-proof load).
 *
 * KIMIX_GRAPH_DB_VERSION is generated by src/graph_db/xmake.lua from
 * version.txt at build time, so it always matches the library build; the
 * fallback below only keeps the header usable by a tool that parses it without
 * the xmake include path.
 *
 * Example:
 *   #include <graph_db/graph_db.h>
 *
 *   kimix::graph_db::Graph graph;
 *   std::byte blob[]{std::byte{'h'}, std::byte{'i'}};
 *   auto *vertex = graph.create_vertex(kimix::span<const std::byte>{blob, 2});
 *   graph.update_content(vertex->guid(), kimix::span<const std::byte>{blob, 1});
 *   kimix::vector<kimix::graph_db::Vertex *> roots = graph.roots();
 */
